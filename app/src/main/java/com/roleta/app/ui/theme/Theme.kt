/**
 * Always uses the Roleta brand palette. Dynamic (wallpaper) color is intentionally
 * not used so the app looks the same on every device.
 */
@Composable
fun RoletaTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
        typography = Typography,
        shapes = Shapes,
        content = content
    )
}
